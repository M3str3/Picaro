//! Packer error types.
//!
//! We use `thiserror` for typed errors with clear messages that can be
//! propagated with `?`, avoiding `panic!`/`unwrap` in the main flow. Each
//! variant maps to a different stage of the process (reading, parsing,
//! validation...).

use std::path::PathBuf;

use crate::audit::AuditError;
use crate::engine::crypto::CryptoError;
use crate::engine::pe::PeError;
use crate::engine::BuildError;

/// Main project error.
#[derive(Debug, thiserror::Error)]
pub enum PackerError {
    /// The plan file could not be read from disk.
    #[error("could not read plan file '{path}': {source}")]
    ReadPlan {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },

    /// The input payload (the PE to be packed) could not be read.
    #[error("could not read input payload '{path}': {source}")]
    ReadInput {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },

    /// The `picaro pack` configuration file could not be read.
    #[error("could not read config file '{path}': {source}")]
    ReadConfig {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },

    /// The `picaro pack` configuration file is not valid YAML or does not match
    /// the config schema.
    #[error("invalid config '{path}': {source}")]
    ParseConfig {
        path: PathBuf,
        #[source]
        source: serde_yml::Error,
    },

    /// The plan generated by `picaro pack` could not be written next to the
    /// artifact.
    #[error("could not write generated plan '{path}': {source}")]
    WritePlan {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },

    /// The stub template could not be read: the custom loader stub
    /// (`build.stub.path`) or the builtin one (`src/engine/templates/main.rs.tpl`).
    #[error("could not read loader stub '{path}': {source}")]
    ReadLoader {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },

    /// The input payload could not be fetched from a URL.
    #[error("could not fetch input payload from '{url}': {source}")]
    FetchInput {
        url: String,
        #[source]
        source: Box<dyn std::error::Error + Send + Sync>,
    },

    /// The file is not valid YAML or does not match the schema.
    #[error("invalid YAML in '{path}': {source}")]
    ParsePlan {
        path: PathBuf,
        #[source]
        source: serde_yml::Error,
    },

    /// The YAML deserialized correctly but violates a business rule.
    #[error("invalid plan: {0}")]
    Validation(String),

    /// A command-line argument is not valid. Distinct from [`Self::Validation`]
    /// (a plan rule), because the message is about the invocation, not the YAML.
    #[error("{0}")]
    Usage(String),

    /// The input payload is not a valid PE.
    #[error("invalid input PE: {0}")]
    Pe(#[from] PeError),

    /// Error while encrypting/decrypting the payload.
    #[error("payload encryption: {0}")]
    Crypto(#[from] CryptoError),

    /// Build engine error (stub rendering and compilation).
    #[error("build error: {0}")]
    Build(#[from] BuildError),

    /// PE resource embedding error.
    #[error("resources: {0}")]
    Resources(#[from] crate::engine::resources::ResourceError),

    /// Error acquiring the per-output build lock.
    #[error("build lock: {0}")]
    BuildLock(#[from] crate::engine::build_lock::BuildLockError),

    /// Artifact signing error.
    #[error("signing: {0}")]
    Signing(#[from] crate::engine::signing::SigningError),

    /// Generic I/O error during the build flow.
    #[error("I/O error: {0}")]
    Io(#[from] std::io::Error),

    /// Static audit error.
    #[error("audit error: {0}")]
    Audit(#[from] AuditError),

    /// `audit --baseline` found a regression.
    ///
    /// The report already explains the changes; the CLI turns this into exit
    /// code 3 so a CI gate can tell a regression from a broken run.
    #[error("baseline regression: {count} change(s)")]
    AuditRegression { count: usize },

    /// `build --verify` rebuilt an artifact whose unsigned hash differs from
    /// the manifest's recorded `predecessor`.
    ///
    /// Exit code 4: the build worked, but it is not the artifact the
    /// reproduction contract promises.
    #[error("reproduction mismatch: expected unsigned sha256 {expected}, built {actual}")]
    VerifyMismatch { expected: String, actual: String },

    /// `build --strict` found a different compiler than the manifest recorded.
    ///
    /// Exit code 5, before compiling: a different `rustc` may still produce the
    /// same bytes, but the contract does not promise it.
    #[error(
        "toolchain mismatch: the manifest was built with '{expected}', this machine has '{actual}'"
    )]
    ToolchainMismatch { expected: String, actual: String },

    /// The operator cancelled an interactive prompt (Esc) before the build.
    ///
    /// Not a failure: the CLI exits 0 without writing anything.
    #[error("cancelled")]
    Cancelled,

    /// The operator asked to go back one wizard section (`Esc` or `:b`).
    ///
    /// Internal to the wizard: the section loop consumes it. If it ever reaches
    /// the CLI, it is treated as a clean cancellation.
    #[error("back")]
    Back,
}

/// `Result` alias used across the crate.
pub type Result<T> = std::result::Result<T, PackerError>;
